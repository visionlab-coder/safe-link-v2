// Fixed loopback-only fixtures. No production DB and no paid AI calls.
import assert from 'node:assert/strict';
import {chromium} from 'playwright-core';
const base='http://127.0.0.1:3100';
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
try {
  const context=await browser.newContext({viewport:{width:390,height:844}});
  const request=context.request;
  const post=(path,data)=>request.post(base+path,{data,headers:{origin:base}});
  let response=await post('/api/auth/worker-quick-login',{name_initials:'W7',phone_last4:'9017',preferred_lang:'ko',site_id:'2'});
  assert.equal(response.status(),200,await response.text());
  response=await request.get(base+'/api/auth/me');
  const me=await response.json();
  assert.ok(me.v3.roles.includes('WORKER'));
  const page=await context.newPage();
  const pageErrors=[];page.on('pageerror',e=>pageErrors.push(e.message));
  await page.goto(base+'/worker?lang=ko');
  await page.getByRole('link',{name:'TBM 작성 · 전파',exact:true}).click();
  await page.getByRole('button',{name:'목록 열기',exact:true}).waitFor();
  assert.ok(page.url().includes('/worker/tbm/create'));
  await page.getByRole('button',{name:'목록 열기',exact:true}).click();
  await page.getByRole('dialog').getByText('451 개 항목',{exact:true}).waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:'/private/tmp/worker-tbm-compose-mobile.png',fullPage:true});
  await page.locator('textarea').first().fill('로컬 테스트 안전모 상태를 확인하세요.');
  const broadcastResponse=page.waitForResponse(r=>r.url().endsWith('/api/tbm/broadcast') && r.request().method()==='POST');
  await page.getByRole('button',{name:'📡 TBM 브로드캐스트',exact:true}).click();
  const published=await broadcastResponse;
  assert.equal(published.status(),200,await published.text());
  const publishedBody=await published.json();
  await page.getByText('전파 완료',{exact:true}).first().waitFor();
  response=await request.get(base+'/api/tbm/today?id='+publishedBody.tbm.id);
  let notice=(await response.json()).tbms[0];
  assert.equal(String(notice.created_by),String(me.user.id));
  response=await post('/api/tbm/broadcast',{content_ko:'차단 테스트',site_id:'999999'});assert.equal(response.status(),403);
  response=await request.get(base+'/api/tbm/nationwide/targets');assert.equal(response.status(),403);
  response=await request.get(base+'/admin',{maxRedirects:0});assert.equal(response.status(),307);
  const session={sessionId:'tbm_worker_qa_'+Date.now(),siteId:'2'};
  response=await post('/api/live/sessions',session);assert.equal(response.status(),200,await response.text());
  response=await post('/api/live/sessions/speaking',session);assert.equal(response.status(),200);
  response=await post('/api/live/translations',{...session,text_ko:'안전모 확인',translations:{}});assert.equal(response.status(),200,await response.text());
  response=await post('/api/live/tbm-draft',{...session,content:'안전모 상태 확인'});assert.equal(response.status(),200,await response.text());
  response=await request.delete(base+'/api/live/sessions?'+new URLSearchParams(session),{headers:{origin:base}});assert.equal(response.status(),200,await response.text());
  response=await post('/api/live/summary',{...session,content_ko:'안전모 상태 확인',summary_ko:'- 안전모 상태 확인'});assert.equal(response.status(),200,await response.text());
  const summary=await response.json();assert.ok(summary.tbmId);
  response=await request.get(base+'/api/tbm/today?id='+summary.tbmId);notice=(await response.json()).tbms[0];
  assert.equal(String(notice.created_by),String(me.user.id));
  assert.equal(notice.summary_ko,'- 안전모 상태 확인');
  assert.equal(notice.content_ko,'안전모 상태 확인');
  await post('/api/auth/logout',{});
  assert.deepEqual(pageErrors,[]);
  console.log('PASS: worker home button, mobile composer, library, real BFF/backend publication, live start/speech/draft/stop/final summary, persisted author/source/summary; cross-site/nationwide/admin-screen denied. AI/microphone quality not tested.');
} finally { await browser.close(); }
