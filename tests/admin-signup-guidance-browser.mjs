import assert from 'node:assert/strict';
import {chromium} from 'playwright-core';
const base=process.env.SQ_TEST_BASE || 'http://127.0.0.1:3100';
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
try {
  const context=await browser.newContext({viewport:{width:390,height:844}});
  const page=await context.newPage();
  let signupRequests=0;
  await page.route('**/api/auth/admin-signup',route=>{signupRequests++;return route.abort();});
  await page.goto(base+'/auth?lang=ko&role=admin');
  await page.getByRole('button',{name:'처음이신가요? 가입하기',exact:true}).click();
  const submit=page.getByRole('button',{name:'가입하기',exact:true});
  const password=page.getByLabel('비밀번호',{exact:true});
  const confirm=page.getByLabel('비밀번호 확인',{exact:true});
  await page.locator('#admin-password-hint').waitFor();
  assert.match(await page.locator('#admin-password-hint').innerText(), /10자 이상/);
  await page.getByRole('textbox',{name:'이메일',exact:true}).fill('test@seowonenc.co.kr');
  await page.getByRole('textbox',{name:'영문 이름 *',exact:true}).fill('TEST USER');
  await password.fill('123456789'); await confirm.fill('123456789');
  assert.equal(await submit.isDisabled(),true);
  assert.match(await page.locator('#admin-signup-requirements').innerText(), /10자 이상/);
  assert.match(await page.locator('#admin-signup-requirements').innerText(), /영문 이름/);
  assert.equal(await page.locator('svg.lucide-circle-check').count(),0);
  await page.screenshot({path:'/private/tmp/admin-signup-guidance-mobile.png',fullPage:true});
  await page.getByRole('checkbox').check();
  await password.fill('1234567890'); await confirm.fill('1234567891');
  await page.getByText('비밀번호가 일치하지 않습니다.',{exact:true}).waitFor();
  assert.equal(await submit.isDisabled(),true);
  await confirm.fill('1234567890');
  await page.waitForFunction(()=>!document.querySelector('#admin-signup-requirements'));
  assert.equal(await submit.isEnabled(),true);
  assert.equal(await page.locator('#admin-password-hint').isVisible(),true);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.getByRole('button',{name:'이미 계정이 있으신가요? 로그인',exact:true}).click();
  await password.fill('short');
  assert.equal(await page.getByRole('button',{name:'로그인하기',exact:true}).isEnabled(),true);
  assert.equal(await page.locator('#admin-password-hint').count(),0);
  assert.equal(signupRequests,0);
  console.log('Mobile UI: persistent hint, all disabled reasons, 9/10 boundary, mismatch, name checkbox, login unaffected; no account created.');
} finally {await browser.close();}
